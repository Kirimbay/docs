#!/bin/bash
# Transparent TCP(+UDP) DNAT for Слон on the Swedish front.
# Run as root on rel-all-work (136.148.213.105 / 10.202.120.2).
#
#   bash apply-tcp-dnat.sh
#   bash apply-tcp-dnat.sh --rollback
#
# Does NOT inspect TLS. Segments from Happ finalMask/fragment pass byte-for-byte
# over HostUp LAN to 10.202.120.54:443.
set -euo pipefail

FRONT_PUB="${FRONT_PUB:-136.148.213.105}"
FRONT_LAN="${FRONT_LAN:-10.202.120.2}"
EXIT_LAN="${EXIT_LAN:-10.202.120.54}"
PORT="${PORT:-443}"
HAPROXY_CFG="${HAPROXY_CFG:-/etc/haproxy/haproxy.cfg}"
UNIT=/etc/systemd/system/slon-dnat.service
SCRIPT=/usr/local/sbin/slon-dnat.sh
STAMP=$(date +%Y%m%d-%H%M%S)
BACKUP_DIR=/root/slon-dnat-backup-$STAMP
STATE=/var/lib/slon-dnat

log(){ printf '[slon-dnat] %s\n' "$*"; }
die(){ printf '[slon-dnat] ERROR: %s\n' "$*" >&2; exit 1; }

need_root(){ [ "$(id -u)" -eq 0 ] || die "run as root on the front"; }

install_rules(){
  # TCP 443 — transparent passthrough (нарезка-safe)
  iptables -t nat -C PREROUTING -d "$FRONT_PUB/32" -p tcp --dport "$PORT" \
    -j DNAT --to-destination "$EXIT_LAN:$PORT" 2>/dev/null \
    || iptables -t nat -I PREROUTING 1 -d "$FRONT_PUB/32" -p tcp --dport "$PORT" \
      -j DNAT --to-destination "$EXIT_LAN:$PORT"
  iptables -t nat -C POSTROUTING -d "$EXIT_LAN/32" -p tcp --dport "$PORT" \
    -j SNAT --to-source "$FRONT_LAN" 2>/dev/null \
    || iptables -t nat -I POSTROUTING 1 -d "$EXIT_LAN/32" -p tcp --dport "$PORT" \
      -j SNAT --to-source "$FRONT_LAN"

  # UDP 443 — same path (HY2 / future); keep if already present
  iptables -t nat -C PREROUTING -d "$FRONT_PUB/32" -p udp --dport "$PORT" \
    -j DNAT --to-destination "$EXIT_LAN:$PORT" 2>/dev/null \
    || iptables -t nat -I PREROUTING 1 -d "$FRONT_PUB/32" -p udp --dport "$PORT" \
      -j DNAT --to-destination "$EXIT_LAN:$PORT"
  iptables -t nat -C POSTROUTING -d "$EXIT_LAN/32" -p udp --dport "$PORT" \
    -j SNAT --to-source "$FRONT_LAN" 2>/dev/null \
    || iptables -t nat -I POSTROUTING 1 -d "$EXIT_LAN/32" -p udp --dport "$PORT" \
      -j SNAT --to-source "$FRONT_LAN"

  iptables -C FORWARD -d "$EXIT_LAN/32" -m conntrack --ctstate DNAT -j ACCEPT 2>/dev/null \
    || iptables -I FORWARD 1 -d "$EXIT_LAN/32" -m conntrack --ctstate DNAT -j ACCEPT
  iptables -C FORWARD -s "$EXIT_LAN/32" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null \
    || iptables -I FORWARD 1 -s "$EXIT_LAN/32" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT

  iptables -t mangle -C FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null \
    || iptables -t mangle -A FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu

  sysctl -w net.ipv4.ip_forward=1 >/dev/null
}

remove_rules(){
  while iptables -t nat -D PREROUTING -d "$FRONT_PUB/32" -p tcp --dport "$PORT" \
    -j DNAT --to-destination "$EXIT_LAN:$PORT" 2>/dev/null; do :; done
  while iptables -t nat -D POSTROUTING -d "$EXIT_LAN/32" -p tcp --dport "$PORT" \
    -j SNAT --to-source "$FRONT_LAN" 2>/dev/null; do :; done
  while iptables -t nat -D PREROUTING -d "$FRONT_PUB/32" -p udp --dport "$PORT" \
    -j DNAT --to-destination "$EXIT_LAN:$PORT" 2>/dev/null; do :; done
  while iptables -t nat -D POSTROUTING -d "$EXIT_LAN/32" -p udp --dport "$PORT" \
    -j SNAT --to-source "$FRONT_LAN" 2>/dev/null; do :; done
}

write_persistent(){
  mkdir -p "$(dirname "$SCRIPT")" "$STATE"
  cat >"$SCRIPT" <<EOF
#!/bin/bash
# Auto-generated by apply-tcp-dnat.sh — do not edit by hand.
set -euo pipefail
FRONT_PUB=$FRONT_PUB
FRONT_LAN=$FRONT_LAN
EXIT_LAN=$EXIT_LAN
PORT=$PORT
$(declare -f install_rules)
install_rules
EOF
  chmod 755 "$SCRIPT"

  cat >"$UNIT" <<EOF
[Unit]
Description=Slon transparent DNAT (TCP/UDP $PORT → $EXIT_LAN, no TLS inspect)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=$SCRIPT
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable --now slon-dnat.service
}

strip_haproxy_443(){
  [ -f "$HAPROXY_CFG" ] || { log "no $HAPROXY_CFG — skip HAProxy edit"; return 0; }
  mkdir -p "$BACKUP_DIR"
  cp -a "$HAPROXY_CFG" "$BACKUP_DIR/haproxy.cfg"
  echo "$BACKUP_DIR" >"$STATE/last-backup"

  python3 - "$HAPROXY_CFG" <<'PY'
import re, sys
path = sys.argv[1]
text = open(path).read()
# Drop frontend that binds :443 / :::443 (tcp443 or tls443), keep the rest.
# Also drop orphan backend b_slon_reality only if frontend tcp443 is removed
# and nothing else references it — keep backend for easy rollback copy in backup.
blocks = re.split(r'(?=^(?:frontend|backend|listen|global|defaults)\b)', text, flags=re.M)
out = []
removed = []
for b in blocks:
    head = b.splitlines()[0] if b.strip() else ''
    if re.match(r'^frontend\s+(tcp443|tls443)\b', head):
        removed.append(head)
        continue
    if re.match(r'^frontend\s+', head) and re.search(r'(?m)^\s*bind\s+\S*:443\b', b):
        # any other frontend binding :443 / :::443
        removed.append(head + ' (bind :443)')
        continue
    out.append(b)
new = ''.join(out)
if not removed:
    print('HAProxy: no :443 frontend found (already clear)')
else:
    open(path, 'w').write(new)
    print('HAProxy removed:', ', '.join(removed))
PY

  if command -v haproxy >/dev/null; then
    haproxy -c -f "$HAPROXY_CFG" || die "haproxy -c failed after edit — restore from $BACKUP_DIR"
    systemctl reload haproxy 2>/dev/null || systemctl restart haproxy
  fi
  # Ensure nothing local owns 443 (DNAT does not need a listener)
  if ss -lnt | awk '{print $4}' | grep -E '(:|::):?443$' >/dev/null 2>&1; then
    log "WARNING: something still listens on :443 — check ss -lntp"
    ss -lntp | grep -E ':443\b' || true
  else
    log "no local LISTEN on :443 — good"
  fi
}

restore_haproxy(){
  local b
  b=$(cat "$STATE/last-backup" 2>/dev/null || true)
  if [ -n "$b" ] && [ -f "$b/haproxy.cfg" ]; then
    cp -a "$b/haproxy.cfg" "$HAPROXY_CFG"
    haproxy -c -f "$HAPROXY_CFG"
    systemctl reload haproxy 2>/dev/null || systemctl restart haproxy
    log "HAProxy restored from $b"
  else
    log "no HAProxy backup recorded — leave cfg as-is"
  fi
}

verify(){
  ping -c1 -W2 "$EXIT_LAN" >/dev/null || die "LAN ping $EXIT_LAN failed"
  log "LAN ping $EXIT_LAN OK"
  if timeout 3 bash -c "echo >/dev/tcp/$EXIT_LAN/$PORT" 2>/dev/null; then
    log "TCP $EXIT_LAN:$PORT reachable from front"
  else
    log "WARNING: TCP $EXIT_LAN:$PORT not open from front (check Xray / nft on 54)"
  fi
  log "nat rules:"
  iptables -t nat -S | grep -E "$FRONT_PUB|$EXIT_LAN" || true
}

do_apply(){
  need_root
  ip -4 addr | grep -q "inet $FRONT_LAN/" || die "LAN $FRONT_LAN not on this host"
  mkdir -p "$BACKUP_DIR" "$STATE"
  iptables-save >"$BACKUP_DIR/iptables.rules.v4"
  strip_haproxy_443
  install_rules
  write_persistent
  # Prefer our script over legacy udp-only helper name
  if [ -f /usr/local/sbin/udp443-to-node20.sh ]; then
    cp -a /usr/local/sbin/udp443-to-node20.sh "$BACKUP_DIR/"
    cat >/usr/local/sbin/udp443-to-node20.sh <<EOF
#!/bin/bash
# Legacy name kept: now delegates to slon-dnat (TCP+UDP).
exec $SCRIPT
EOF
    chmod 755 /usr/local/sbin/udp443-to-node20.sh
  fi
  if command -v netfilter-persistent >/dev/null; then
    netfilter-persistent save >/dev/null 2>&1 || true
  fi
  verify
  log "DONE: $FRONT_PUB:$PORT → $EXIT_LAN:$PORT via LAN (SNAT $FRONT_LAN), no TLS inspect"
  log "backup: $BACKUP_DIR"
}

do_rollback(){
  need_root
  systemctl disable --now slon-dnat.service 2>/dev/null || true
  remove_rules
  restore_haproxy
  log "rollback complete (TCP DNAT removed; HAProxy restore attempted)"
  iptables -t nat -S | grep -E "$FRONT_PUB|$EXIT_LAN" || log "no remaining slon nat rules"
}

case "${1:-}" in
  --rollback|-r) do_rollback ;;
  ""|--apply|-a) do_apply ;;
  -h|--help) sed -n '2,12p' "$0" ;;
  *) die "unknown arg: $1" ;;
esac
